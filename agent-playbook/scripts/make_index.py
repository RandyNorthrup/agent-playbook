#!/usr/bin/env python3
"""Write INDEX.json: every script here with its purpose, usage line, needs and side effects.

  make_index.py            rewrite INDEX.json beside the scripts
  make_index.py --check    exit 1 when INDEX.json is missing or out of date (nothing is written)
  make_index.py --print    print the index instead of writing it
  make_index.py --dir DIR  do the same for another folder of scripts (the media tools: --dir ../media)

Each entry is read from the script itself: the purpose is its argparse description (the first line of its
docstring), the usage is its parser's usage line, and needs / side effects are its NEEDS and EFFECTS
constants. So the index can't drift from the scripts: a test runs --check.
Side effects: none, clipboard, network, files (it writes or rewrites files), browser (it acts on the
owner's Chrome or one of its dialogs).
"""
import importlib
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import common  # noqa: E402

NEEDS = []
EFFECTS = ["files"]
MODULES = {"common.py": "Shared helpers the scripts import (requests, TSV, time, X length, Chrome, clipboard); not a command.",
           "mcommon.py": "Shared helpers the media tools import (ffmpeg, fonts, image measures, the format numbers); not a command."}
KNOWN_EFFECTS = {"none", "clipboard", "network", "files", "browser"}


def build_parser():
    ap = common.make_parser(__doc__, __file__, "PROG [--dir DIR] [--check | --print]")
    ap.add_argument("--dir", default=HERE, metavar="DIR", help="the folder of scripts to index (default: this one)")
    ap.add_argument("--check", action="store_true", help="exit 1 when INDEX.json is out of date")
    ap.add_argument("--print", action="store_true", dest="show", help="print the index, write nothing")
    return ap


def script_names(folder=HERE):
    return sorted(n for n in os.listdir(folder) if n.endswith(".py") and n not in MODULES)


def load(folder, name):
    """Import one script from `folder` by its path, so a name that also exists in another folder can't be picked up."""
    if os.path.abspath(folder) == HERE:
        return importlib.import_module(name[:-3])
    spec = importlib.util.spec_from_file_location(name[:-3], os.path.join(folder, name))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def entry(name, folder=HERE):
    mod = load(folder, name)
    parser = mod.build_parser()
    effects = list(mod.EFFECTS)
    if not effects or set(effects) - KNOWN_EFFECTS:
        raise ValueError("%s: EFFECTS must be a non-empty list from %s" % (name, sorted(KNOWN_EFFECTS)))
    usage = " ".join(parser.format_usage().split())
    return {"name": name, "purpose": parser.description.replace("%%", "%"), "usage": usage[len("usage: "):] if usage.startswith("usage: ") else usage,
            "needs": list(mod.NEEDS), "side_effects": effects}


def build(folder=HERE):
    return {"about": "Generated by make_index.py from each script's own parser; do not edit by hand.",
            "exit_codes": {"0": "worked", "1": "failed (message on stderr)", "2": "usage error", "3": "an optional module is missing"},
            "scripts": [entry(n, folder) for n in script_names(folder)],
            "modules": [{"name": n, "purpose": p} for n, p in sorted(MODULES.items()) if os.path.exists(os.path.join(folder, n))]}


def main(argv=None):
    a = build_parser().parse_args(argv)
    if not os.path.isdir(a.dir):
        common.die("no such folder: %s" % a.dir)
    index_file = os.path.join(a.dir, "INDEX.json")
    index = build(a.dir)
    text = json.dumps(index, indent=1, ensure_ascii=False) + "\n"
    if a.show:
        common.safe_stdio()
        sys.stdout.write(text)
        return 0
    if a.check:
        try:
            with open(index_file, encoding="utf-8") as fh:
                current = json.load(fh)
        except (OSError, ValueError):
            common.die("INDEX.json is missing or unreadable; run make_index.py")
        if current != index:
            stale = [e["name"] for e in index["scripts"] if e not in current.get("scripts", [])]
            gone = [e.get("name") for e in current.get("scripts", []) if e not in index["scripts"]]
            common.die("INDEX.json is out of date (changed or new: %s; stale: %s); run make_index.py"
                       % (", ".join(stale) or "-", ", ".join(map(str, gone)) or "-"))
        print("INDEX.json is current (%d scripts)" % len(index["scripts"]))
        return 0
    common.write_atomic(index_file, text)
    print("wrote", index_file, len(index["scripts"]), "scripts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
